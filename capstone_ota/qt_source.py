"""Central's frame sender. Fault scheduling belongs to the external verifier."""
import argparse
import json
import socket
import struct


def frame(speed, counter, rpm=1500, gear=3, warnings=0):
    if any(type(v) is not int for v in (speed, counter, rpm, gear, warnings)):
        raise ValueError('vehicle inputs must be integers')
    if not (0 <= speed <= 3000 and 0 <= rpm <= 9000 and 0 <= gear <= 6
            and 0 <= counter <= 255 and 0 <= warnings <= 255):
        raise ValueError('vehicle input out of range')
    raw = struct.pack('>HHBBB', speed, rpm, gear, warnings, counter)
    crc = 0
    for value in raw + b'\x00\x21':
        crc ^= value
        for _ in range(8):
            crc = ((crc << 1) ^ 7 if crc & 128 else crc << 1) & 255
    return {'id': 0x200, 'data': (raw + bytes([crc])).hex()}


def send(message, udp_host=None, udp_port=None, channel=None):
    if channel is not None:
        with socket.socket(socket.AF_CAN, socket.SOCK_RAW, socket.CAN_RAW) as bus:
            bus.bind((channel,))
            bus.settimeout(1)
            bus.send(struct.pack('=IB3x8s', message['id'], 8, bytes.fromhex(message['data'])))
    else:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as bus:
            bus.sendto(json.dumps(message).encode(), (udp_host or '127.0.0.1', udp_port))
    return {'sent': 1}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    transport = parser.add_mutually_exclusive_group(required=True)
    transport.add_argument('--udp-port', type=int)
    transport.add_argument('--can-channel')
    parser.add_argument('--udp-host', default='127.0.0.1')
    parser.add_argument('--frame', required=True, help='fixed CAN frame as JSON, generated by verifier')
    args = parser.parse_args()
    try:
        message = json.loads(args.frame)
        if (not isinstance(message, dict) or set(message) != {'id', 'data'} or message['id'] != 0x200
                or not isinstance(message['data'], str) or len(bytes.fromhex(message['data'])) != 8):
            raise ValueError('invalid source frame')
        print(json.dumps(send(message, args.udp_host, args.udp_port, args.can_channel)))
        return 0
    except (OSError, ValueError, TypeError) as exc:
        print(json.dumps({'passed': False, 'error': str(exc)}))
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
